"""Generate the public Python stub from its owning facade declarations."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "python/trace_index/__init__.py"
DESTINATION = SOURCE.with_suffix(".pyi")


class Stub(ast.NodeTransformer):
    def visit_FunctionDef(self, node: ast.FunctionDef) -> ast.FunctionDef:
        # Exception attributes must remain visible to type checkers.
        attrs = []
        for item in node.body:
            if isinstance(item, ast.Assign) and len(item.targets) == 1:
                target = item.targets[0]
                if (
                    isinstance(target, ast.Attribute)
                    and isinstance(target.value, ast.Name)
                    and target.value.id == "self"
                    and target.attr in {"report", "result"}
                ):
                    attrs.append(item)
        docstring = node.body[:1] if ast.get_docstring(node) is not None else []
        node.body = docstring + attrs + [ast.Expr(ast.Constant(Ellipsis))]
        return node

    def visit_ClassDef(self, node: ast.ClassDef) -> ast.ClassDef:
        docstring = node.body[:1] if ast.get_docstring(node) is not None else []
        node.body = docstring + [
            self.visit(item)
            for item in node.body
            if isinstance(item, (ast.AnnAssign, ast.FunctionDef))
        ]
        if not node.body:
            node.body = [ast.Expr(ast.Constant(Ellipsis))]
        return node


def generate() -> str:
    tree = ast.parse(SOURCE.read_text())
    # IDEs reading stubs see the same local docstrings as runtime help().
    # Shared bootstrap knowledge is composed at runtime from the native module.
    body = tree.body[:1] if ast.get_docstring(tree) is not None else []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            if isinstance(node, ast.ImportFrom) and node.module == "_native":
                # Explicit re-exports, not implementation-only imports.
                node.names = [ast.alias(alias.name, alias.name) for alias in node.names]
            body.append(node)
        elif isinstance(node, (ast.ClassDef, ast.AnnAssign)):
            body.append(Stub().visit(node))
        elif isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            body.append(Stub().visit(node))
        elif isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__all__"
            for target in node.targets
        ):
            body.append(node)
    return (
        "# Generated by scripts/generate_python_stubs.py; do not edit.\n"
        + ast.unparse(ast.Module(body=body, type_ignores=[]))
        + "\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != content:
            raise SystemExit(
                "Python stub is stale; run scripts/generate_python_stubs.py"
            )
    else:
        DESTINATION.write_text(content)
